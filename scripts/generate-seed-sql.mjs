#!/usr/bin/env node
/**
 * Emits the seed migration from src/lib/data/spots.ts.
 *
 * Hand-transcribing fourteen entries with long prose fields into SQL is a
 * transcription-error machine — a dropped apostrophe or a mangled accent
 * would sit in the database unnoticed. Generating it means the TypeScript
 * seed stays the single source, and the migration can be regenerated if it
 * changes.
 *
 * Run: npm run seed:sql
 */
import { mkdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const SOURCE = resolve(root, "src/lib/data/spots.ts");
const OUT = resolve(root, "supabase/migrations/20260817090100_seed_spots.sql");

/* ------------------------------------------------- load the TS seed ---- */

/**
 * Node can strip types, but not resolve the `@/` path alias — so the
 * type-only import is removed and the annotation dropped, leaving plain
 * JS that imports cleanly.
 */
const temp = resolve(root, ".seed-source.tmp.mts");
const source = readFileSync(SOURCE, "utf8")
  .replace(/^import type .*$/m, "")
  .replace(/export const SPOTS: Spot\[\]/, "export const SPOTS");

writeFileSync(temp, source);

let SPOTS;
try {
  ({ SPOTS } = await import(pathToFileURL(temp).href));
} finally {
  rmSync(temp, { force: true });
}

/* ----------------------------------------------------------- escaping -- */

/** Standard SQL literal quoting: double every embedded single quote. */
const q = (value) => `'${String(value).replace(/'/g, "''")}'`;
const json = (value) => `${q(JSON.stringify(value))}::jsonb`;
const num = (value) => Number(value).toString();

/* ------------------------------------------------------------- emit ---- */

const lines = [];

lines.push(
  "-- ---------------------------------------------------------------------",
  "-- Seed spots.",
  "--",
  "-- GENERATED by scripts/generate-seed-sql.mjs from src/lib/data/spots.ts.",
  "-- Do not edit by hand — regenerate with `npm run seed:sql`.",
  "--",
  "-- Idempotent: re-running updates existing rows by slug rather than",
  "-- erroring or duplicating, so it is safe to replay against a database",
  "-- that already has some of these.",
  "-- ---------------------------------------------------------------------",
  "",
  "set search_path = public, extensions;",
  "",
);

for (const spot of SPOTS) {
  lines.push(
    `-- ${spot.name} (${spot.region}, ${spot.country})`,
    "insert into public.spots (",
    "  slug, name, region, country, lat, lng,",
    "  category, difficulty, access,",
    "  summary, description, watch_out, best_window, walk_in_km, photos, created_at",
    ") values (",
    `  ${q(spot.slug)}, ${q(spot.name)}, ${q(spot.region)}, ${q(spot.country)},`,
    `  ${num(spot.lat)}, ${num(spot.lng)},`,
    `  ${q(spot.category)}, ${q(spot.difficulty)}, ${q(spot.access)},`,
    `  ${q(spot.summary)},`,
    `  ${q(spot.description)},`,
    `  ${q(spot.watchOut)},`,
    `  ${q(spot.bestWindow)},`,
    `  ${num(spot.walkInKm)},`,
    `  ${json(spot.photos)},`,
    `  ${q(spot.addedAt)}::timestamptz`,
    ")",
    "on conflict (slug) do update set",
    "  name = excluded.name,",
    "  region = excluded.region,",
    "  country = excluded.country,",
    "  lat = excluded.lat,",
    "  lng = excluded.lng,",
    "  category = excluded.category,",
    "  difficulty = excluded.difficulty,",
    "  access = excluded.access,",
    "  summary = excluded.summary,",
    "  description = excluded.description,",
    "  watch_out = excluded.watch_out,",
    "  best_window = excluded.best_window,",
    "  walk_in_km = excluded.walk_in_km,",
    "  photos = excluded.photos;",
    "",
  );
}

// Notes are replaced wholesale per spot: they have no natural key, and
// re-running should not stack duplicates.
lines.push(
  "-- ------------------------------------------------------------- notes --",
  "",
  "delete from public.spot_notes",
  "where spot_id in (select id from public.spots where slug in (",
  SPOTS.map((s) => `  ${q(s.slug)}`).join(",\n"),
  "));",
  "",
);

for (const spot of SPOTS) {
  for (const note of spot.notes) {
    lines.push(
      "insert into public.spot_notes (spot_id, author, body, noted_on)",
      `select id, ${q(note.author)}, ${q(note.body)}, ${q(note.date)}::date`,
      `from public.spots where slug = ${q(spot.slug)};`,
      "",
    );
  }
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lines.join("\n"));

const noteCount = SPOTS.reduce((n, s) => n + s.notes.length, 0);
console.log(
  `wrote ${OUT.replace(root + "/", "")} — ${SPOTS.length} spots, ${noteCount} notes`,
);
